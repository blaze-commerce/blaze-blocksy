<?php
/**
 * docs/MODULES.md generator and its freshness gate.
 *
 * @package Blocksy_Child
 */

namespace Blaze\Child\Tools;

/**
 * Renders the module catalogue from modules/<id>/module.json (deterministic: sorted, no timestamps).
 */
final class ModulesMd {

	const FILE = 'docs/MODULES.md';

	/** Section order. */
	const STATUSES = [ 'stable', 'beta', 'deprecated', 'legacy', 'planned' ];

	/**
	 * The full Markdown text.
	 *
	 * @param Context $ctx Context.
	 * @return string
	 */
	public static function render( Context $ctx ): string {
		$by_status = array_fill_keys( self::STATUSES, [] );
		foreach ( $ctx->modules() as $name => $mod ) {
			$m = $mod['data'];
			if ( null !== $m && isset( $by_status[ $m['status'] ?? '' ] ) ) {
				$by_status[ $m['status'] ][ $name ] = $m;
			}
		}

		$total  = array_sum( array_map( 'count', $by_status ) );
		$counts = [];
		foreach ( $by_status as $status => $mods ) {
			$counts[] = count( $mods ) . ' ' . $status;
		}

		$out   = [];
		$out[] = '# Modules';
		$out[] = '';
		$out[] = 'Generated by `php tools/gen-modules-md.php` from `modules/*/module.json`. Do not edit by hand;';
		$out[] = 'CI fails when this file is stale.';
		$out[] = '';
		$out[] = "{$total} modules: " . implode( ', ', $counts ) . '.';

		foreach ( $by_status as $status => $mods ) {
			if ( ! $mods ) {
				continue;
			}
			ksort( $mods, SORT_STRING );
			$out[] = '';
			$out[] = '## ' . ucfirst( $status ) . ' (' . count( $mods ) . ')';
			$out[] = '';
			$out[] = '| id | title | surfaces | owner | default |';
			$out[] = '|---|---|---|---|---|';
			foreach ( $mods as $name => $m ) {
				$surfaces = array_map(
					function ( $s ): string {
						return '`' . self::cell( (string) $s ) . '`';
					},
					is_array( $m['surfaces'] ?? null ) ? $m['surfaces'] : []
				);
				$out[]    = sprintf(
					'| `%s` | %s | %s | %s | %s |',
					self::cell( $name ),
					self::cell( (string) ( $m['title'] ?? '' ) ),
					$surfaces ? implode( ', ', $surfaces ) : '-',
					'' !== (string) ( $m['owner'] ?? '' ) ? self::cell( (string) $m['owner'] ) : '-',
					empty( $m['default'] ) ? 'off' : 'on'
				);
			}
		}

		return implode( "\n", $out ) . "\n";
	}

	/**
	 * A table-safe cell.
	 *
	 * @param string $text Text.
	 * @return string
	 */
	private static function cell( string $text ): string {
		return str_replace( [ '|', "\r", "\n" ], [ '\\|', ' ', ' ' ], $text );
	}

	/**
	 * docs/MODULES.md equals what the generator would write.
	 *
	 * @param Context $ctx Context.
	 * @return array
	 */
	public static function modules_md_fresh( Context $ctx ): array {
		if ( $ctx->read( self::FILE ) === self::render( $ctx ) ) {
			return Context::gate( 'modules_md_fresh', 'fail', true, self::FILE . ' is up to date' );
		}
		return Context::gate( 'modules_md_fresh', 'fail', false, self::FILE . ' is stale or missing; run php tools/gen-modules-md.php', [ self::FILE ] );
	}
}
